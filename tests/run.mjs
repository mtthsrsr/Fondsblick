a.product.breakdowns.holdings.rows=[{name:'Cycle',isin:parent.product.isin,weight:100}];assert.equal(aggregate([parent],'holdings',false,[parent,a]).coverage,0);
assert.throws(()=>validateState({version:1,entries:[b,b]}));
